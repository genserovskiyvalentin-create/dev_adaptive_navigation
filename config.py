#!/usr/bin/env python3
"""
Конфигурация алгоритма перехвата с АДАПТИВНЫМ упреждением.
Оптимизировано для устранения орбитального вращения (перелётов).
"""
from dataclasses import dataclass

@dataclass
class InterceptConfig:
    # ---------------- Камера ----------------
    FRAME_W: int = 1024
    FRAME_H: int = 768
    FOV_H_DEG: float = 90.0
    CAMERA_TO_BODY_EULER: tuple = (0.0, 0.0, -1.5708)
    CAMERA_FLIP_Y: bool = False

    # ---------------- Гимбал ----------------
    GIMBAL_TELEMETRY_HZ: int = 100
    


    
    # ---------------- Пропорциональная навигация (АДАПТИВНАЯ) ----------------
    N_NAV: float = 2.0              # Стартовое значение N
    N_MIN: float = 1.0              # Минимальный предел N
    N_MAX: float = 3.0              # СНИЖЕНО с 3.0 до 1.5 (строгий лимит против орбиты)
    N_ADAPT_RATE: float = 0.2      # корость адаптации N. Чем больше — тем быстрее N меняется.
    
        # LOS-скорость теперь считается в градусах/сек (мировая СК), а не px/s
    LOS_DEADZONE_DEG_S: float = 7.0     # Порог LOS-скорости (deg/s), ниже которого N уменьшается. Зона «цель почти в центре».
    LOS_OVERSHOOT_DEG_S: float = 30.0    # Порог LOS-скорости, выше которого N резко падает. Защита от перелёта/орбиты.
  
    
    TTC_CAP_SEC: float = 8.0        # Максимальное значение TTC (time-to-collision). Ограничивает дальность упреждения.
    MAX_LEAD_DEG: float = 25.0       # Максимальное угловое упреждение в градусах. Жёсткий лимит.
    MAX_LEAD_PX: float = 300.0      # Максимальное упреждение в пикселях. Лимит после перевода углов в px.
    
    # ---------------- Гистерезис TTC ----------------
    TTC_GROWTH_THRESHOLD: float = 0.07 # Минимальная скорость роста площади (d(lnA)/dt), при которой цель считается «приближающейся».
    TTC_HYSTERESIS_FRAMES: int = 3 # Сколько кадров подряд нужно подтвердить «приближение», чтобы включить TTC. Защита от дребезга.
    
    # ---------------- Ограничение скорости нарастания lead ----------------
    MAX_LEAD_RATE_DEG_S: float = 4.0  # СНИЖЕНО для максимальной плавности
    
    # ---------------- Конус действия алгоритма ----------------
    #MAX_CONE_DEG: float = 45.0
    
    # ---------------- Заморозка на финальном сближении ----------------
    FREEZE_SIZE_RATIO: float = 0.6
    
    # ---------------- Фильтр Калмана ----------------
    KF_ANGLE_PROCESS_NOISE: float = 20.0 # Шум процесса для LOS-фильтра (азимут/тангаж). Больше — фильтр быстрее реагирует, но шумнее.
    KF_ANGLE_MEASUREMENT_NOISE: float = 5.0 # Шум измерения для LOS-фильтра. Меньше — фильтр больше доверяет измерениям.
    KF_AREA_PROCESS_NOISE: float = 2.0 # Шум процесса для фильтра площади (TTC).
    KF_AREA_MEASUREMENT_NOISE: float = 0.05 # Шум измерения для фильтра площади.
    MAX_KF_DT_SEC: float = 0.05 # Максимальный dt между кадрами для Калмана. Защита от скачков при зависании.
    MIN_AREA_PX: float = 25.0 # Минимальная площадь рамки цели. Меньше — цель игнорируется (шум/артефакты).
    
    # ---------------- PD-регулятор и управление ----------------
    INVERT_YAW: bool = False
    INVERT_ROLL: bool = False
    INVERT_PITCH: bool = True
    
    # КРИТИЧЕСКИ ВАЖНО для устранения орбиты:
    KP: float = 0.15   # Пропорциональный коэффициент PD-регулятора. Определяет «жёсткость» слежения.
    KD: float = 0.05   # Дифференциальный коэффициент. Гасит колебания, добавляет демпфирование.
    
    MAX_RATE_DEG_S: float = 180.0 # Максимальная угловая скорость дрона (deg/s) в режиме ACRO.
    ACRO_RP_RATE_DEG_S: float = 180.0 # талонная скорость ACRO, при которой RC = 2000. Калибровка стика.
    REF_TARGET_SIZE: int = 400 # Эталонный размер цели (px) для gain_scale.
    MIN_GAIN_SCALE: float = 0.2 # Минимальный множитель усиления PD при крупной цели.
    MAX_RATE_CMD_RATE_DEG_S2: float = 400.0  # Максимальная скорость нарастания команды (deg/s²). Сглаживает рывки.
    
    THRUST_RC: int = 1500 # Значение RC-канала газа во время TAKEOFF и TRACKING
    TAKEOFF_TIME_SEC: float = 0.1# Длительность фазы TAKEOFF (сек).
    SAFE_ANGLE_LIMIT_DEG: float = 30.0 # Ограничение углов при взлёте (защита от переворота).
    JOY_DEADZONE: float = 0.05 # Мёртвая зона джойстика.
    SWITCH_THRESHOLD: float = 0.5 # Порог переключателя «авто/ручной» на джойстике.
    TARGET_LOST_FRAMES: int = 100 #Сколько кадров без цели → переход в MANUAL.
    MAVLINK_CONN: str = "udp:127.0.0.1:14550"
    GST_UDP_PORT: int = 5600
    GAZEBO_CAMERA_TOPIC: str = "/world/iris_runway/model/iris_with_wings/link/camera_link/sensor/camera/image/enable_streaming"